"""Design the CDR3 with BoltzGen instead of grafting one from the archive.

Why. Our generator grafts an archived CDR3 onto an archived framework and
reaches design_iiptm 0.375. The field's median is 0.664 and the per-epoch best
0.757 (FINDINGS 10); at CDR3 length 7, where our last candidate sat, the field
runs 0.57 median and 0.71 best. No amount of tuning closes that: grafting
recombines sequences that were never selected for binding this target.

What the leaders are almost certainly doing. BoltzGen is not only the scorer
the validators run -- it is a binder *design* model. Its CLI carries
`--num_designs` ("commonly something like 10,000"), the protocols
`design-diverse` and `design-adherence`, a `nanobody-anything` protocol, and
example specs under `example/nanobody_scaffolds/` that fix an antibody
framework and design its CDRs against a target. Sequences generated by the
model that then scores them score well by construction, which is the simplest
explanation for a field median that tripled between 2026-10-29 and 11-06 while
the maximum barely moved.

What this script builds. A design spec that keeps everything the validator
checks and designs only what it does not:

  - the framework is a real archived sequence that already clears the V and J
    germline floors and carries the VHH hallmarks, so germline identity is
    preserved by construction rather than hoped for;
  - CDR1 and CDR2 stay fixed. They are scored against the V reference, and in
    the field's own top quartile the germline CDR1 is 45% of sequences against
    31% in the bottom quartile;
  - the CDR3 is designed at exactly the length the epoch imposes;
  - the CDR3's first 2 and last 3 residues stay fixed, because they are not
    ours: the V segment encodes the head (IGHV3-23 ends ...YYCAK, IGHV3-66
    ...YYCAR) and the J segment the last three. FINDINGS 7ter measured what
    happens when they are free -- 58% of candidates refused on J identity, 38%
    of unmutated pairs losing the V call.

Indexing. BoltzGen's res_index is the canonical mmcif index, sequential from 1
-- NOT the author numbering, and NOT the IMGT numbering that NanoBodyBuilder2
writes into its PDB output. The indices here are therefore computed as offsets
into the plain sequence. That assumption is the one thing in this file that
cannot be checked offline, so `boltzgen check` must be run on the spec before
any GPU time: it writes back the structure with the design mask applied, and
--print-mask shows the designed span. Run that first and confirm the span is
the CDR3.

Usage:
    python -m scripts.design_nanobody --epoch 26238 --frameworks 4
    python -m scripts.design_nanobody --allowed-v IGHV3-66 --cdr3 16
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

from nova_lab import DATA_DIR, REPO_ROOT
from nova_lab.cdr3_generators import J_TAIL
from nova_lab.config import (MIN_HUMAN_J_IDENTITY, MIN_HUMAN_V_IDENTITY,
                             NANOBODY_TARGET)
from nova_lab.nanobodies import germline_identity, is_vhh, regions

# The target, exactly as the validator's own scoring yaml builds it
# (nova-upstream config/config.yaml, nanobody section).
TARGET_STRUCTURE = "8AOK"
TARGET_CHAIN = "A"
TARGET_RES_INDEX = "1..115"
TARGET_BINDING_SITE = ("37,39,41..44,46,49,51,56,59,94..96,98,100,"
                       "104..108")

# Residues at each end of the CDR3 that belong to a germline segment and so
# must not be designed. Measured in FINDINGS 7ter.
V_HEAD = 2
J_TAIL_FIXED = 3  # the J segment covers the last three; J_TAIL=4 keeps a margin


def framework_donors(target: str, allowed_v: str, n: int) -> pd.DataFrame:
    """Archived sequences that already clear every germline gate for this epoch."""
    df = pd.read_parquet(DATA_DIR / "dataset" / f"{target}_nanobodies.parquet")
    from scripts.propose_nanobody import GERMLINE_MARGIN, rank_sum
    df["true_rank_sum"] = rank_sum(df)
    ok = df[(df["v_identity"] >= MIN_HUMAN_V_IDENTITY + GERMLINE_MARGIN)
            & (df["j_identity"] >= MIN_HUMAN_J_IDENTITY)
            & df["v_genes"].str.split(",").apply(lambda g: allowed_v in g)]
    ok = ok.nsmallest(n * 40, "true_rank_sum")
    # The best-ranked archive entries are near-duplicates of each other, so
    # take one per distinct framework: four scaffolds that share a framework
    # explore one neighbourhood four times.
    keep, seen = [], set()
    for row in ok.itertuples():
        vhh, _ = is_vhh(row.sequence)
        r = regions(row.sequence)
        if not (vhh and r):
            continue
        signature = r["FR1"] + r["FR2"] + r["FR3"] + r["CDR1"] + r["CDR2"]
        if signature in seen:
            continue
        seen.add(signature)
        keep.append(row.sequence)
        if len(keep) >= n:
            break
    return pd.DataFrame({"sequence": keep})


def scaffold_spec(sequence: str, cdr3_length: int, structure_path: str) -> tuple[dict, dict]:
    """The scaffold half of the spec: fix the framework, design the CDR3.

    Returns (spec, report). The CDR3 is rebuilt to the epoch's length by
    removing the donor's designable middle and inserting exactly as many
    designed residues as are needed, so the result is the imposed length
    whatever the donor's own CDR3 was.
    """
    r = regions(sequence)
    cdr3 = r["CDR3"]
    start = sequence.index(cdr3) + 1  # 1-based, sequential
    head_end = start + V_HEAD - 1
    designable_start = head_end + 1
    designable_count = cdr3_length - V_HEAD - J_TAIL_FIXED
    if designable_count < 1:
        raise ValueError(
            f"CDR3 length {cdr3_length} leaves {designable_count} designable "
            f"residues once the V head ({V_HEAD}) and J tail ({J_TAIL_FIXED}) "
            f"are held fixed. Nothing to design.")
    donor_middle_end = start + len(cdr3) - J_TAIL_FIXED - 1

    spec = {
        "path": structure_path,
        "include": [{"chain": {"id": "B"}}],
        "design": [{"chain": {"id": "B",
                              "res_index": f"{designable_start}..{donor_middle_end}"}}],
        "structure_groups": [
            {"group": {"id": "B", "visibility": 2}},
            {"group": {"id": "B", "visibility": 0,
                       "res_index": f"{designable_start}..{donor_middle_end}"}},
        ],
        # Take out the donor's own designable middle, then insert exactly the
        # number of residues the epoch's length calls for.
        "exclude": [{"chain": {"id": "B",
                               "res_index": f"{designable_start}..{donor_middle_end}"}}],
        "design_insertions": [{"insertion": {"id": "B", "res_index": designable_start,
                                             "num_residues": f"{designable_count}..{designable_count}"}}],
    }
    identity = germline_identity(sequence)
    report = {
        "framework": sequence,
        "cdr3_donor": cdr3,
        "cdr3_target_length": cdr3_length,
        "fixed_head": cdr3[:V_HEAD],
        "fixed_tail": cdr3[-J_TAIL_FIXED:],
        "designed_residues": designable_count,
        "res_index_designed": f"{designable_start}..{donor_middle_end}",
        "v_identity": round(identity["V"]["identity_pct"], 2) if identity else None,
        "j_identity": round(identity["J"]["identity_pct"], 2) if identity else None,
        "cdr1": r["CDR1"], "cdr2": r["CDR2"],
    }
    return spec, report


def top_level_spec(scaffold_paths: list[str], target_cif: str) -> dict:
    """Target plus scaffolds, in the shape example/nanobody/penguinpox.yaml uses."""
    return {
        "entities": [
            {"file": {
                "path": target_cif,
                "include": [{"chain": {"id": TARGET_CHAIN,
                                       "res_index": TARGET_RES_INDEX}}],
                "binding_types": [{"chain": {"id": TARGET_CHAIN,
                                             "binding": TARGET_BINDING_SITE}}],
            }},
            {"file": {"path": scaffold_paths}},
        ]
    }


def renumber_sequentially(pdb: Path) -> int:
    """Renumber residues 1..N in place, and return N.

    NanoBodyBuilder2 writes IMGT numbering, which has gaps: scaffold0 runs
    1-9, 11, ... to 128 for 120 residues. BoltzGen's res_index is the canonical
    mmcif index, sequential from 1, and its README is explicit that the author
    numbering is "incorrect" for this purpose -- but what its PDB parser does
    with an author-numbered file is not something we can check without running
    it. Renumbering makes the two readings coincide, so the spec is right
    either way instead of right if we guessed the parser correctly.
    """
    lines, mapping, out = pdb.read_text().splitlines(True), {}, []
    for line in lines:
        if line.startswith(("ATOM", "HETATM")):
            key = line[22:27]  # residue number plus insertion code
            if key not in mapping:
                mapping[key] = len(mapping) + 1
            out.append(f"{line[:22]}{mapping[key]:>4} {line[27:]}")
        else:
            out.append(line)
    pdb.write_text("".join(out))
    return len(mapping)


# ImmuneBuilder lives in the TNP virtualenv, not the miner's: the same split
# scripts.tnp_developability works around for the TNP binary.
FOLDER_PYTHON = Path("/home/user/venv-tnp/bin/python")


def fold(sequence: str, out: Path) -> Path:
    """NanoBodyBuilder2 structure for the framework, as BoltzGen's input."""
    import subprocess
    if not FOLDER_PYTHON.exists():
        raise SystemExit(
            f"NanoBodyBuilder2 needs {FOLDER_PYTHON}, which is where ImmuneBuilder "
            f"is installed. Without it there is no structure and no design spec.")
    out.parent.mkdir(parents=True, exist_ok=True)
    proc = subprocess.run(
        [str(FOLDER_PYTHON), "-c",
         "import sys\n"
         "from ImmuneBuilder import NanoBodyBuilder2\n"
         "NanoBodyBuilder2().predict({'H': sys.argv[1]}).save(sys.argv[2])",
         sequence, str(out)],
        capture_output=True, text=True)
    if proc.returncode != 0 or not out.exists():
        raise RuntimeError(f"NanoBodyBuilder2 failed: {proc.stderr[-600:]}")
    n = renumber_sequentially(out)
    if n != len(sequence):
        raise ValueError(
            f"{out.name}: the structure has {n} residues for a {len(sequence)}-residue "
            f"sequence, so sequence offsets do not index it. Refusing to emit a spec "
            f"whose res_index would point at the wrong residues.")
    return out


THREE_TO_ONE = {
    "ALA": "A", "ARG": "R", "ASN": "N", "ASP": "D", "CYS": "C", "GLN": "Q",
    "GLU": "E", "GLY": "G", "HIS": "H", "ILE": "I", "LEU": "L", "LYS": "K",
    "MET": "M", "PHE": "F", "PRO": "P", "SER": "S", "THR": "T", "TRP": "W",
    "TYR": "Y", "VAL": "V",
}


def structure_sequence(pdb: Path) -> str:
    """The one-letter sequence as the renumbered structure holds it."""
    seen, out = None, []
    for line in pdb.read_text().splitlines():
        if line.startswith("ATOM"):
            number = line[22:26]
            if number != seen:
                seen = number
                out.append(THREE_TO_ONE.get(line[17:20].strip(), "X"))
    return "".join(out)


def verify_span(pdb: Path, report: dict) -> None:
    """Prove the res_index span is the CDR3's designable middle, on the file itself.

    This is the check that matters, and it runs offline: read the residues the
    span actually names out of the structure BoltzGen will read, and compare
    them to the donor's CDR3 minus the fixed head and tail. `boltzgen check`
    validates BoltzGen's own parsing and is still worth running, but it does
    not have to be trusted to catch an arithmetic slip here.
    """
    sequence = structure_sequence(pdb)
    if sequence != report["framework"]:
        raise ValueError(f"{pdb.name}: the structure's sequence is not the framework's")
    low, high = (int(x) for x in report["res_index_designed"].split(".."))
    named = sequence[low - 1:high]
    expected = report["cdr3_donor"][V_HEAD:len(report["cdr3_donor"]) - J_TAIL_FIXED]
    if named != expected:
        raise ValueError(
            f"{pdb.name}: res_index {low}..{high} names {named!r}, but the CDR3's "
            f"designable middle is {expected!r}. The spec would design the wrong "
            f"residues.")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--epoch", type=int, help="read the challenge from the chain")
    parser.add_argument("--allowed-v", help="skip the chain and use this V gene")
    parser.add_argument("--cdr3", type=int, help="skip the chain and use this length")
    parser.add_argument("--target", default=NANOBODY_TARGET[0])
    parser.add_argument("--frameworks", type=int, default=4)
    parser.add_argument("--out", type=Path, default=Path("inputs/design"))
    parser.add_argument("--nova-dir", type=Path, default=Path("/home/user/nova-upstream"))
    parser.add_argument("--fold", action="store_true",
                        help="also build the structures with NanoBodyBuilder2 "
                             "(a minute per framework on CPU)")
    args = parser.parse_args()

    if args.allowed_v and args.cdr3:
        allowed_v, cdr3_length = args.allowed_v, args.cdr3
    else:
        from scripts.check_nanobody import resolve_epoch
        params = resolve_epoch(args.epoch)
        allowed_v, cdr3_length = params["allowed_v"], params["allowed_cdr3_length"]
        print(f"epoch {params['epoch']}: V {allowed_v}, CDR3 {cdr3_length}")

    donors = framework_donors(args.target, allowed_v, args.frameworks)
    if donors.empty:
        raise SystemExit(f"no compliant framework calls {allowed_v}")
    print(f"{len(donors)} compliant VHH frameworks for {allowed_v}")

    args.out.mkdir(parents=True, exist_ok=True)
    reports, scaffold_files = [], []
    for i, sequence in enumerate(donors["sequence"]):
        structure = args.out / f"scaffold{i}.pdb"
        spec, report = scaffold_spec(sequence, cdr3_length, structure.name)
        if args.fold:
            fold(sequence, structure)
            verify_span(structure, report)
            print(f"  scaffold{i}: structure -> {structure}, span verified against it")
        path = args.out / f"scaffold{i}.yaml"
        path.write_text(_as_yaml(spec))
        scaffold_files.append(path.name)
        report["scaffold"] = path.name
        reports.append(report)

    target_cif = args.nova_dir / "data" / "structures" / f"{TARGET_STRUCTURE}.cif"
    spec_path = args.out / "design_spec.yaml"
    spec_path.write_text(_as_yaml(top_level_spec(scaffold_files, target_cif.name)))
    (args.out / "report.json").write_text(json.dumps(reports, indent=2))

    print(f"\nspec -> {spec_path}")
    print(pd.DataFrame(reports)[["scaffold", "cdr3_donor", "fixed_head", "fixed_tail",
                                 "designed_residues", "res_index_designed",
                                 "v_identity", "j_identity"]].to_string(index=False))
    print(f"\nCheck the indexing BEFORE spending GPU time -- res_index is the")
    print(f"sequential mmcif index, not IMGT, and that is the one assumption")
    print(f"this script cannot verify offline:")
    print(f"    boltzgen check {spec_path}")
    print(f"then open the written structure and confirm the designed span is the CDR3.")


def _as_yaml(obj) -> str:
    """Minimal YAML writer: the specs are plain dicts, lists and scalars.

    Avoids adding PyYAML to the miner's dependencies for four files.
    """
    def emit(value, indent=0):
        pad = "  " * indent
        if isinstance(value, dict):
            out = []
            for k, v in value.items():
                if isinstance(v, (dict, list)):
                    out.append(f"{pad}{k}:")
                    out.append(emit(v, indent + 1))
                else:
                    out.append(f"{pad}{k}: {v}")
            return "\n".join(out)
        if isinstance(value, list):
            out = []
            for item in value:
                if isinstance(item, dict):
                    body = emit(item, indent + 1)
                    first, *rest = body.split("\n")
                    out.append(f"{pad}- {first.strip()}")
                    out.extend(rest)
                else:
                    out.append(f"{pad}- {item}")
            return "\n".join(out)
        return f"{pad}{value}"
    return emit(obj) + "\n"


if __name__ == "__main__":
    main()
